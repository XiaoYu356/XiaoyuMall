# LLM 生成同义问法的提示词（json_mode：提示词里需含 "JSON" 字样）
_LLM_SYSTEM_PROMPT = """你是电商客服知识库编辑。给定一条 FAQ 标准问题，生成 3 条用户真实的同义问法。
要求：
- 口语化、措辞多样，可用"咋""能不能""多少"等日常说法，不要书面腔
- 意思与原问题一致，不要引入原问题之外的新信息
- 每条 5~20 字，不要以"请问"开头，也不要与原问题雷同
严格只输出 JSON 对象（不要任何多余说明），格式：{"similar_questions": ["问法1", "问法2", "问法3"]}"""


def _gen_llm() -> ChatOpenAI:
    """同义问法生成用模型：快速模型 + 低温度 + 关闭思考（与 consolidator 配置一致）。"""
    return ChatOpenAI(
        model=settings.OPENAI_MODEL_FAST,
        api_key=settings.OPENAI_API_KEY,
        base_url=settings.OPENAI_API_BASE,
        temperature=0.2,
        extra_body={"enable_thinking": False},
    )


def _extract_json_object(text: str) -> dict:
    """宽容解析模型输出为 JSON 对象（容忍 ```json 围栏）。"""
    text = text.strip()
    if text.startswith("```"):
        text = text.split("```")[1]
        if text.startswith("json"):
            text = text[4:]
    return json.loads(text.strip())


async def _llm_similar(llm: ChatOpenAI, question: str) -> list[str]:
    """单条调 LLM 生成同义问法，返回字符串列表（解析失败/格式不对抛异常，由调用方兜底）。"""
    response = await llm.bind(response_format={"type": "json_object"}).ainvoke(
        [("system", _LLM_SYSTEM_PROMPT), ("human", question)]
    )
    data = _extract_json_object(response.content)
    items = data.get("similar_questions")
    if not isinstance(items, list) or not items:
        raise ValueError(f"LLM 返回缺少 similar_questions 列表: {response.content[:120]}")
    return [str(x).strip() for x in items if str(x).strip()]


def _merge_similar(question: str, fallback: list[str], generated: list[str],
                   limit: int = 5) -> list[str]:
    """合并兜底 + LLM 生成：丢弃与原问题相同的，去重保序，上限 limit 条。"""
    seen: set[str] = set()
    merged: list[str] = []
    for cand in [*fallback, *generated]:
        text = str(cand).strip()
        if not text or text == question.strip() or text in seen:
            continue
        seen.add(text)
        merged.append(text)
        if len(merged) >= limit:
            break
    return merged


async def gen_similar_questions() -> list[list[str]]:
    """逐条生成同义问法；单条失败回退人工兜底并告警，不中断整体流程。"""
    total = len(FAQ_ITEMS)
    llm = _gen_llm()
    result: list[list[str]] = []
    llm_ok = 0
    for i, item in enumerate(FAQ_ITEMS, start=1):
        question = item["question"]
        generated: list[str] = []
        try:
            generated = await _llm_similar(llm, question)
            llm_ok += 1
        except Exception as e:  # noqa: BLE001 —— 单条失败必须兜底继续
            logger.warning("第 %d/%d 条 LLM 生成失败，使用人工兜底: %s", i, total, e)
        merged = _merge_similar(question, FALLBACK_SIMILAR.get(question, []), generated)
        result.append(merged)
        logger.info("同义问法 第%d/%d 条完成（LLM 生成 %d 条，合并后 %d 条）",
                    i, total, len(generated), len(merged))
    logger.info("LLM 生成成功 %d/%d 条（失败条目已用 FALLBACK_SIMILAR 兜底）", llm_ok, total)
    return result


async def _remove_legacy_concrete_index() -> None:
    """迁移兜底（一次性）：v2 遗留的 mall_faq 是普通索引，ES 不允许创建与其同名的
    alias（invalid_alias_name_exception），须删除后 switch_faq_alias 才能建 alias。
    该索引 19 条数据与 faq_seed.py 同源、可随时用 scripts/import_faq.py 重建；
    删除后对外检索统一走 alias（§13.2）。幂等：mall_faq 已是 alias 时直接跳过。
    """
    async with httpx.AsyncClient(timeout=5.0) as client:
        alias = await client.get(f"{settings.ES_URL}/_alias/mall_faq")
        if alias.status_code == 200:
            logger.info("mall_faq 已是 alias，无需迁移兜底")
            return
        head = await client.head(f"{settings.ES_URL}/mall_faq")
        if head.status_code != 200:
            return  # 既非 alias 也非普通索引（全新环境），无事可做
        resp = await client.delete(f"{settings.ES_URL}/mall_faq")
        if resp.status_code != 200:
            raise RuntimeError(f"删除 v2 遗留索引 mall_faq 失败: {resp.text[:200]}")
        logger.warning("已删除 v2 遗留普通索引 mall_faq（数据源自 faq_seed.py 可重建），"
                       "为创建同名 alias 让路")


async def main() -> int:
    total = len(FAQ_ITEMS)
    logger.info("=== FAQ 知识库 v3 构建开始：共 %d 条种子 ===", total)

    # 1) 生成每条种子的相似问题
    similar_all = await gen_similar_questions()

    # 2) 向量化并组装文档：question + similar 一起送 embed_texts（内部自动 10 条分批）
    docs: list[dict] = []
    for i, (item, similar) in enumerate(zip(FAQ_ITEMS, similar_all), start=1):
        vectors = await embed_texts([item["question"], *similar])
        docs.append({
            "question": item["question"],
            "similar_questions": similar,
            "answer": item["answer"],
            "category": item["category"],
            "tags": TAGS[i - 1],
            "version": 3,
            # 只存 question 的向量（问法对问法匹配更准）；similar 仅参与 BM25，本版不存向量
            "question_vector": vectors[0],
        })
        logger.info("向量化 第%d/%d 条完成（维度=%d）", i, total, len(vectors[0]))

    # 3) 重建索引（删 mall_faq_v3 → 按 §13.2 mapping 重建）
    await ensure_faq_index_v3(recreate=True)

    # 4) bulk 导入
    imported = await bulk_index_faq_v3(docs)
    logger.info("bulk 导入完成：%d 条", imported)
    assert imported == total, f"导入条数不符：期望 {total} 实际 {imported}"

    # 5) alias 原子切换：mall_faq → mall_faq_v3（旧索引解绑；含一次性迁移兜底）
    await _remove_legacy_concrete_index()
    await switch_faq_alias()

    # 6) 冒烟检索：命中售后/退款类条目即视为通过
    query = "退货政策"
    hits = await search_faq_v3(query, await embed_text(query), top_k=3)
    logger.info("冒烟检索 '%s' 命中 %d 条：", query, len(hits))
    for rank, h in enumerate(hits, start=1):
        print(f"top{rank}: [{h['category']}] {h['question']} (score={h['score']:.4f})")
    assert hits, "冒烟检索未命中任何文档"
    logger.info("=== FAQ 知识库 v3 构建完成 ===")
    return 0


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
